export const schemas: Record<string, Schema> = {
  SocialProfileCareer: obj({
    company: str,
    role: str,
    startedOn: nullable(date),
    endedOn: nullable(date),
    description: str,
  }),
  SocialProfileCareerInput: obj({
    company: text(1, 200),
    role: text(1, 200),
    startedOn: nullable(date),
    endedOn: nullable(date),
    description: text(0, 500),
  }, ["company", "role"]),
  Profile: obj(profileProps),
  ProfileDetail: obj({ ...profileProps, following: bool, offered: bool }),
  Offer: obj({
    id: uuid,
    sender: obj({ id: str, displayName: str, companyName: nullable(str), headline: str, avatarUrl: nullable(str) }),
    recipient: person,
    message: str,
    posting: nullable(obj({ id: uuid, title: str, company: str, imageUrl: nullable(str) })),
    status: enumOf("SENT", "READ", "ACCEPTED", "DECLINED"),
    readAt: nullable(dateTime),
    createdAt: dateTime,
  }),
  OfferMessage: obj({ id: uuid, offerId: uuid, sender: person, body: str, createdAt: dateTime }),
  ProfileLink: obj({
    id: uuid,
    kind: LINK_KIND,
    url: str,
    title: str,
    status: str,
    fitCount: int,
    aiRead: bool,
    createdAt: dateTime,
  }),
  Device: obj({ token: str, platform: enumOf("ios", "android") }),
  Notification: obj({
    id: uuid,
    type: { type: "string", description: "OFFER, COMMENT, DEADLINE, AI_DONE, APPLICATION_STAGE" },
    title: str,
    body: str,
    target: {
      type: "object",
      description: "Navigation target. Empty object when missing.",
      properties: {
        kind: { type: "string", description: "offer, post, posting, calendar, activity (application id), conversation" },
        id: str,
      },
      additionalProperties: true,
    },
    readAt: nullable(dateTime),
    createdAt: dateTime,
  }),
  UserSettings: obj({
    notifyDeadline: bool,
    notifyOffer: bool,
    notifyComment: bool,
    notifyAiDone: bool,
    notifyApplicationStage: bool,
    locale: str,
    profilePublic: bool,
    careerStatusVisibility: enumOf("everyone", "followers", "private"),
    hideFromCurrentCompany: bool,
    contactVisibility: enumOf("accepted", "followers", "everyone", "private"),
    defaultTone: enumOf("as_is", "professional", "confident", "concise", "technical", "friendly"),
    chatRetentionDays: nullable(int),
    allowAiReadMyFiles: bool,
    defaultEffort: enumOf("LOW", "MEDIUM", "HIGH", "MAX"),
    confirmBeforeEdit: bool,
    aiAccessMode: enumOf("ALWAYS_ASK", "AUTO", "BYPASS"),
  }),
  Post: obj({
    id: uuid,
    author: obj({ id: str, displayName: str, employer: bool, companyName: nullable(str) }),
    category: POST_CATEGORY,
    title: str,
    body: str,
    imageUrls: arr(str),
    commentCount: int,
    viewCount: int,
    createdAt: dateTime,
  }),
  Comment: obj({ id: uuid, author: person, body: str, parentId: nullable(uuid), createdAt: dateTime }),
};
